import {readdirSync, readFileSync} from 'node:fs';
import {delimiter, join, relative, resolve} from 'node:path';
import ts from 'typescript';
import {describe, expect, it} from 'vitest';

const pkgDir = join(import.meta.dirname, '..');
const root = join(pkgDir, '../..');
const LIBRARY_DOCS = ['README.md', 'docs/migration-from-dynamoose.md'];
// DOCS_SITE_DIR lists directories of docs-site pages (path-delimiter separated). A page carrying the
// sync marker is a copy of a library doc or TypeDoc output, so only the authored pages are gated here.
const SITE_DOCS = (process.env.DOCS_SITE_DIR ?? '')
  .split(delimiter)
  .filter(Boolean)
  .flatMap((dir) => {
    const pages = readdirSync(dir).filter((f) => f.endsWith('.md'));
    if (pages.length === 0) throw new Error(`${dir}: DOCS_SITE_DIR holds no markdown file`);
    return pages.map((f) => resolve(dir, f));
  })
  .filter((doc) => !readFileSync(doc, 'utf8').includes('generated by pnpm orm:sync'));
const DOCS = [...LIBRARY_DOCS, ...SITE_DOCS];
// A block in another language is not compiled, so only languages that cannot hold TypeScript are allowed.
const LANGUAGES = new Set(['ts', 'typescript', 'sh', 'text']);

interface Snippet {
  doc: string;
  line: number;
  code: string;
}

/** The top-level fenced blocks of a markdown file. */
function blocksOf(doc: string): Array<Snippet & {lang: string}> {
  const lines = readFileSync(resolve(root, doc), 'utf8').split('\n');
  const blocks: Array<Snippet & {lang: string}> = [];
  for (let i = 0; i < lines.length; i++) {
    const open = /^```(\S*)$/.exec(lines[i]!);
    if (!open) continue;
    const end = lines.indexOf('```', i + 1);
    if (end === -1) throw new Error(`${doc}:${i + 1}: unclosed code block`);
    blocks.push({doc, line: i + 1, lang: open[1]!, code: lines.slice(i + 1, end).join('\n')});
    i = end;
  }
  return blocks;
}

const blocks = DOCS.flatMap(blocksOf);
const snippets = blocks.filter((b) => b.lang === 'ts' || b.lang === 'typescript');
// Counted on the raw text, indented fences included, so a block the extractor misses fails the count.
const fenceCount = (doc: string) =>
  readFileSync(resolve(root, doc), 'utf8').match(/^[ \t]*```(?:ts|typescript)[ \t]*$/gm)?.length ??
  0;

// Each snippet is a virtual module inside the package, so `zod` and the SDK resolve from its node_modules.
// The package's entry points resolve to its source, compiled with the package's own compiler options.
function compile(list: readonly Snippet[]): {compiled: number; errors: string[]} {
  const config = ts.parseJsonConfigFileContent(
    {
      extends: './tsconfig.json',
      files: [],
      compilerOptions: {
        moduleDetection: 'force',
        paths: {
          'dynotable-orm': ['./src/index.ts'],
          'dynotable-orm/zod': ['./src/zod/index.ts'],
          // dynamoose 4.2.0 from npm: the only dynamoose the docs compare against.
          dynamoose: ['./node_modules/dynamoose/dist/index.d.ts']
        }
      }
    },
    ts.sys,
    pkgDir
  );
  const configErrors = config.errors.filter((d) => d.code !== 18002 && d.code !== 18003);
  if (configErrors.length > 0)
    throw new Error(ts.flattenDiagnosticMessageText(configErrors[0]!.messageText, '\n'));

  const files = new Map(list.map((s, i) => [join(pkgDir, `__docs__/snippet-${i}.ts`), s]));
  const host = ts.createCompilerHost(config.options);
  const {fileExists, readFile, getSourceFile} = host;
  host.fileExists = (f) => files.has(f) || fileExists(f);
  host.readFile = (f) => files.get(f)?.code ?? readFile(f);
  host.getSourceFile = (f, lang, ...rest) => {
    const s = files.get(f);
    return s ? ts.createSourceFile(f, s.code, lang) : getSourceFile(f, lang, ...rest);
  };
  const program = ts.createProgram([...files.keys()], config.options, host);

  const errors = ts.getPreEmitDiagnostics(program).map((d) => {
    const text = ts.flattenDiagnosticMessageText(d.messageText, '\n');
    const s = d.file && files.get(d.file.fileName);
    if (!s || d.start === undefined)
      return d.file ? `${relative(root, d.file.fileName)}: ${text}` : text;
    const {line} = d.file!.getLineAndCharacterOfPosition(d.start);
    return `${s.doc}:${s.line + 1 + line}: ${text}`;
  });
  return {compiled: [...files.keys()].filter((f) => program.getSourceFile(f)).length, errors};
}

describe('docs snippets', () => {
  it('uses only languages that are compiled or cannot hold TypeScript', () => {
    expect(
      blocks.filter((b) => !LANGUAGES.has(b.lang)).map((b) => `${b.doc}:${b.line} '${b.lang}'`)
    ).toEqual([]);
  });

  it('extracts every TypeScript block of each doc', () => {
    for (const doc of DOCS) {
      const extracted = snippets.filter((s) => s.doc === doc).length;
      // A site page may hold no TypeScript at all.
      if (LIBRARY_DOCS.includes(doc)) expect(extracted, doc).toBeGreaterThan(0);
      expect(extracted, doc).toBe(fenceCount(doc));
    }
  });

  it('compiles every TypeScript block against the package', () => {
    const {compiled, errors} = compile(snippets);
    expect(errors).toEqual([]);
    expect(compiled).toBe(snippets.length);
  }, 60_000);

  // The gate is only worth its green if a wrong snippet turns it red.
  it('reports a snippet that does not type-check, at its doc line', () => {
    const {errors} = compile([
      {doc: 'probe.md', line: 10, code: "import {model} from 'dynotable-orm';\n\nmodel(1);"}
    ]);
    expect(errors).toHaveLength(1);
    expect(errors[0]).toMatch(/^probe\.md:13: /);
  }, 60_000);
});
